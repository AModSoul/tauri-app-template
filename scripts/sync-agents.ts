// Syncs agent-agnostic instructions into the layouts each editor and agent expects.
//
// Sources of truth:
//   AGENTS.md            -> CLAUDE.md (imports AGENTS.md via `@AGENTS.md`)
//   .agents/skills/<n>/  -> .claude/skills/<n>/
//   .agents/mcp.json     -> .mcp.json         (Claude Code)
//                        -> .cursor/mcp.json  (Cursor)
//                        -> .vscode/mcp.json  (VS Code, which uses `servers` and needs `type`)
//
// Outputs are gitignored and regenerated on install, merge and checkout.

import { existsSync } from "node:fs";
import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

type McpServer =
  | { type?: "stdio"; command: string; args?: string[]; env?: Record<string, string> }
  | { type: "http"; url: string; headers?: Record<string, string> };

type McpConfig = { mcpServers?: Record<string, McpServer> };

const root = path.resolve(import.meta.dirname, "..");
const agentsSkillsDir = path.join(root, ".agents/skills");
const claudeSkillsDir = path.join(root, ".claude/skills");
const agentsMcpFile = path.join(root, ".agents/mcp.json");

const claudeMd = `<!-- Generated by scripts/sync-agents.ts. Do not edit; edit AGENTS.md instead. -->
@AGENTS.md
`;

await writeFile(path.join(root, "CLAUDE.md"), claudeMd);

await rm(claudeSkillsDir, { recursive: true, force: true });

let skills: string[] = [];
if (existsSync(agentsSkillsDir)) {
  const entries = await readdir(agentsSkillsDir, { withFileTypes: true });
  skills = entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name);

  await mkdir(claudeSkillsDir, { recursive: true });
  for (const skill of skills) {
    await cp(path.join(agentsSkillsDir, skill), path.join(claudeSkillsDir, skill), {
      recursive: true,
    });
  }
}

const servers: Record<string, McpServer> = existsSync(agentsMcpFile)
  ? ((JSON.parse(await readFile(agentsMcpFile, "utf8")) as McpConfig).mcpServers ?? {})
  : {};

/** Cursor infers the transport: `command` means stdio, `url` means HTTP. */
const withoutType = (server: McpServer) => {
  const { type: _type, ...rest } = server;
  return rest;
};

/** VS Code wants an explicit `type` on every server. */
const withType = (server: McpServer) =>
  "url" in server ? server : { ...server, type: "stdio" as const };

const mapServers = <T>(map: (server: McpServer) => T) =>
  Object.fromEntries(Object.entries(servers).map(([name, server]) => [name, map(server)]));

const outputs: [file: string, config: object][] = [
  [".mcp.json", { mcpServers: servers }],
  [".cursor/mcp.json", { mcpServers: mapServers(withoutType) }],
  [".vscode/mcp.json", { servers: mapServers(withType) }],
];

for (const [file, config] of outputs) {
  const target = path.join(root, file);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, `${JSON.stringify(config, null, 2)}\n`);
}

console.log(
  `agents:sync wrote CLAUDE.md, ${skills.length} skill(s) to .claude/skills and ${Object.keys(servers).length} MCP server(s) to ${outputs.map(([file]) => file).join(", ")}`,
);
